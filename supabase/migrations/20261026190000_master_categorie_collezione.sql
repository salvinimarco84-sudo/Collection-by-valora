-- VALORA: master categorie collezione e gerarchia tema/sottotema.
-- Da applicare esclusivamente al progetto TEST tramite pipeline migration.
-- Non modifica né riclassifica automaticamente gli oggetti esistenti.

begin;

create table if not exists collection.master_categorie_collezione (
  codice_categoria text primary key,
  descrizione text not null check (length(btrim(descrizione)) > 0),
  icona text not null default 'category_outlined',
  colore_hex text not null default '#D6B15E'
    check (colore_hex ~ '^#[0-9A-Fa-f]{6}$'),
  ordine_menu integer not null default 100,
  visibile boolean not null default true,
  creato_il timestamptz not null default now(),
  aggiornato_il timestamptz not null default now()
);

comment on table collection.master_categorie_collezione is
  'Master delle categorie principali mostrate nel menu COLLEZIONE. La chiave codice_categoria è stabile e non dipende dalla descrizione.';

create table if not exists collection.temi_collezione (
  id_tema bigint generated by default as identity primary key,
  codice_categoria text not null references collection.master_categorie_collezione(codice_categoria)
    on update cascade on delete restrict,
  codice_tema text not null,
  descrizione text not null check (length(btrim(descrizione)) > 0),
  ordine integer not null default 100,
  attivo boolean not null default true,
  creato_il timestamptz not null default now(),
  aggiornato_il timestamptz not null default now(),
  constraint uq_temi_collezione_categoria_codice unique (codice_categoria, codice_tema),
  constraint uq_temi_collezione_categoria_descrizione unique (codice_categoria, descrizione)
);

comment on table collection.temi_collezione is
  'Categoria 1: temi ricavati dal campo Tema dei metadati. I sottotemi (es. Polizia) restano nei metadati e non vengono promossi a tema.';

create table if not exists collection.oggetto_collezione_categoria (
  codice_oggetto bigint primary key references collection.master_oggetti(codice_oggetto)
    on delete cascade,
  codice_categoria text not null references collection.master_categorie_collezione(codice_categoria)
    on update cascade on delete restrict,
  id_tema bigint null references collection.temi_collezione(id_tema)
    on update cascade on delete set null,
  fonte_assegnazione text not null default 'MANUALE'
    check (fonte_assegnazione in ('MANUALE','METADATI','IMPORTAZIONE','VERIFICA')),
  stato_verifica text not null default 'DA_VERIFICARE'
    check (stato_verifica in ('DA_VERIFICARE','VERIFICATO','CONFLITTO')),
  aggiornato_il timestamptz not null default now(),
  constraint ck_oggetto_tema_stessa_categoria check (id_tema is null or true)
);

comment on table collection.oggetto_collezione_categoria is
  'Assegnazione esplicita dell’oggetto alla categoria principale e, facoltativamente, al tema. Nessuna classificazione basata solo sulla descrizione.';

create index if not exists ix_temi_collezione_categoria_ordine
  on collection.temi_collezione(codice_categoria, attivo, ordine);

create index if not exists ix_oggetto_collezione_categoria_tema
  on collection.oggetto_collezione_categoria(codice_categoria, id_tema);

-- La relazione tema/categoria viene validata con trigger, evitando di assegnare
-- un tema appartenente a una categoria principale diversa.
create or replace function collection.verifica_tema_categoria_oggetto()
returns trigger
language plpgsql
set search_path = collection, pg_temp
as $$
declare
  tema_categoria text;
begin
  if new.id_tema is null then
    return new;
  end if;

  select codice_categoria into tema_categoria
  from collection.temi_collezione
  where id_tema = new.id_tema;

  if tema_categoria is null or tema_categoria <> new.codice_categoria then
    raise exception 'Il tema selezionato non appartiene alla categoria principale indicata';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_verifica_tema_categoria_oggetto
  on collection.oggetto_collezione_categoria;

create trigger trg_verifica_tema_categoria_oggetto
before insert or update of codice_categoria, id_tema
on collection.oggetto_collezione_categoria
for each row execute function collection.verifica_tema_categoria_oggetto();

-- RLS attiva: le policy restringono l’accesso ai ruoli autenticati.
alter table collection.master_categorie_collezione enable row level security;
alter table collection.temi_collezione enable row level security;
alter table collection.oggetto_collezione_categoria enable row level security;

drop policy if exists "authenticated read master categorie collezione"
  on collection.master_categorie_collezione;
create policy "authenticated read master categorie collezione"
  on collection.master_categorie_collezione for select to authenticated using (true);

drop policy if exists "authenticated manage master categorie collezione"
  on collection.master_categorie_collezione;
create policy "authenticated manage master categorie collezione"
  on collection.master_categorie_collezione for all to authenticated
  using (true) with check (true);

drop policy if exists "authenticated read temi collezione"
  on collection.temi_collezione;
create policy "authenticated read temi collezione"
  on collection.temi_collezione for select to authenticated using (true);

drop policy if exists "authenticated manage temi collezione"
  on collection.temi_collezione;
create policy "authenticated manage temi collezione"
  on collection.temi_collezione for all to authenticated
  using (true) with check (true);

drop policy if exists "authenticated read assegnazioni collezione"
  on collection.oggetto_collezione_categoria;
create policy "authenticated read assegnazioni collezione"
  on collection.oggetto_collezione_categoria for select to authenticated using (true);

drop policy if exists "authenticated manage assegnazioni collezione"
  on collection.oggetto_collezione_categoria;
create policy "authenticated manage assegnazioni collezione"
  on collection.oggetto_collezione_categoria for all to authenticated
  using (true) with check (true);

commit;
